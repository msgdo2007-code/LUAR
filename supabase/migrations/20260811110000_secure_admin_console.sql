create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin')),
  granted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_email text not null,
  kind text not null check (kind in ('suggestion', 'problem', 'review')),
  message text not null check (char_length(message) between 10 and 1800),
  rating smallint check (rating between 1 and 5),
  publish_authorized boolean not null default false,
  status text not null default 'pending' check (status in ('pending', 'reviewing', 'approved', 'rejected', 'implemented')),
  admin_response text check (admin_response is null or char_length(admin_response) <= 1800),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null check (char_length(action) between 3 and 80),
  target_type text not null check (char_length(target_type) between 2 and 40),
  target_id text not null check (char_length(target_id) between 1 and 254),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);

create index if not exists admin_feedback_status_created_idx on public.admin_feedback(status, created_at desc);
create index if not exists admin_feedback_user_idx on public.admin_feedback(user_id, created_at desc);
create index if not exists admin_audit_logs_created_idx on public.admin_audit_logs(created_at desc);

