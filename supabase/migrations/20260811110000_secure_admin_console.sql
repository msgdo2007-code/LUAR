create or replace function public.is_luar_admin(p_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select p_user_id is not null and exists (
    select 1 from public.user_roles role_row
    where role_row.user_id = p_user_id and role_row.role = 'admin'
  );
$$;

revoke all on function public.is_luar_admin(uuid) from public, anon;
grant execute on function public.is_luar_admin(uuid) to authenticated;

drop policy if exists user_roles_admin_select on public.user_roles;
create policy user_roles_admin_select on public.user_roles for select to authenticated
using (public.is_luar_admin());

drop policy if exists admin_feedback_owner_insert on public.admin_feedback;
create policy admin_feedback_owner_insert on public.admin_feedback for insert to authenticated
with check (user_id = auth.uid() and lower(user_email) = lower(coalesce(auth.jwt()->>'email', '')));
drop policy if exists admin_feedback_admin_select on public.admin_feedback;
create policy admin_feedback_admin_select on public.admin_feedback for select to authenticated
using (public.is_luar_admin());
drop policy if exists admin_feedback_admin_update on public.admin_feedback;
create policy admin_feedback_admin_update on public.admin_feedback for update to authenticated
using (public.is_luar_admin()) with check (public.is_luar_admin());

drop policy if exists admin_audit_admin_select on public.admin_audit_logs;
create policy admin_audit_admin_select on public.admin_audit_logs for select to authenticated
using (public.is_luar_admin());

grant select on public.user_roles to authenticated;
grant select, insert, update on public.admin_feedback to authenticated;
grant select on public.admin_audit_logs to authenticated;
grant usage, select on sequence public.admin_feedback_id_seq to authenticated;

